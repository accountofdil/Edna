SELECT 
	oi.product_id,
	p.product_name,
	SUM(oi.total_sales) AS total_sales,
	COUNT(o.order_id) AS total_orders
FROM orders AS o
JOIN order_items AS oi
ON o.order_id = oi.order_id
JOIN products AS p
ON p.product_id = oi.product_id
GROUP BY 1, 2
ORDER BY 3 DESC
