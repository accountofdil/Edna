CREATE TABLE categories(
					category_id INT PRIMARY KEY,
					category_name VARCHAR(20));

CREATE TABLE customers(
					customer_id INT PRIMARY KEY,
					first_name VARCHAR(20),
					last_name VARCHAR(20),
					state VARCHAR(20));

CREATE TABLE sellers(
				seller_id INT PRIMARY KEY,
				seller_name VARCHAR(25),
				origin VARCHAR(15));

CREATE TABLE products(
					product_id INT PRIMARY KEY,
					product_name VARCHAR(50),
					price FLOAT,
					cogs FLOAT,
					category_id INT,
					CONSTRAINT fk_product_category FOREIGN KEY (category_id) REFERENCES categories(category_id));

CREATE TABLE orders(
				order_id INT PRIMARY KEY,
				order_date DATE, 
				customer_id INT, 
				seller_id INT, 
				order_status VARCHAR(15),
				CONSTRAINT fk_orders_customers FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
				CONSTRAINT fk_orders_sellers FOREIGN KEY (seller_id) REFERENCES sellers(seller_id));

CREATE TABLE order_items(
					order_item_id INT PRIMARY KEY,
					order_id INT,
					product_id INT,
					quantity INT,
					price_per_unit FLOAT,
					CONSTRAINT fk_orderitems_orders FOREIGN KEY (order_id) REFERENCES orders(order_id),
					CONSTRAINT fk_orderitems_products FOREIGN KEY (product_id) REFERENCES products(product_id));

CREATE TABLE payments(
					payment_id INT PRIMARY KEY,
					order_id INT,
					payment_date DATE,
					payment_status VARCHAR(20),
					CONSTRAINT fk_payments_orders FOREIGN KEY (order_id) REFERENCES orders(order_id));

CREATE TABLE shippings(
					shipping_id INT PRIMARY KEY,
					order_id INT,
					shipping_date DATE,
					return_date DATE,
					shipping_providers VARCHAR(15),
					delivery_status VARCHAR(15),
					CONSTRAINT fk_shippings_orders FOREIGN KEY (order_id) REFERENCES orders(order_id));

CREATE TABLE inventory(
					inventory_id INT PRIMARY KEY,
					product_id INT,
					stock INT, 
					warehouse_id INT,
					last_stock_date DATE,
					CONSTRAINT fk_inventory_products FOREIGN KEY (product_id) REFERENCES products(product_id));

