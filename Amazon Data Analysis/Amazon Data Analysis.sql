/*
Find the top 5 sellers based on total sales value
Include both successful and failed orders; display their percentage of successful orders
*/

WITH top_sellers
AS
	(SELECT 
		s.seller_id, 
		s.seller_name,
		SUM(oi.total_sales) AS total_sales
	FROM orders AS o
	JOIN sellers AS s
	ON o.seller_id = s.seller_id
	JOIN order_items AS oi
	ON oi.order_id = o.order_id
	GROUP BY 1, 2
	ORDER BY 3 DESC
	LIMIT 5),
seller_reports
AS
	(SELECT 
		o.seller_id,
		ts.seller_name,
		o.order_status,
		COUNT(*) AS total_orders
	FROM orders AS o
	JOIN top_sellers AS ts
	ON ts.seller_id = o.seller_id
	WHERE 
		o.order_status NOT IN ('Inprogress', 'Returned')
	GROUP BY 1, 2, 3)
SELECT 
	seller_id,
	seller_name,
	SUM(CASE WHEN order_status = 'Completed' THEN total_orders ELSE 0 END) AS completed_orders,
	SUM(CASE WHEN order_status = 'Cancelled' THEN total_orders ELSE 0 END) AS cancelled_orders,
	SUM(total_orders) AS total_orders,
	SUM(CASE WHEN order_status = 'Completed' THEN total_orders ELSE 0 END)::numeric / SUM(total_orders)::numeric * 100 AS percentage_of_successful_orders
FROM seller_reports
GROUP BY 1, 2;

/*
Calculate the profit margin for each product (price minus cost of goods sold)
Rank products by their profit margin, showing highest to lowest
*/

SELECT 
	product_id,
	product_name,
	profit_margin,
	DENSE_RANK() OVER(ORDER BY profit_margin DESC) AS product_ranking
FROM
	(SELECT 
		p.product_id,
		p.product_name,
		SUM(total_sales - (p.cogs * oi.quantity)) AS profit,
		SUM(total_sales - (p.cogs * oi.quantity)) / sum(total_sales) * 100 AS profit_margin
	FROM order_items AS oi
	JOIN products AS p
	ON oi.product_id = p.product_id
	GROUP BY 1, 2) AS t1

