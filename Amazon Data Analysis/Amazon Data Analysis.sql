/*
Calculate total revenue generated by each product category
Include the percentage contribution of each category to total revenue
*/

SELECT 
	p.category_id,
	c.category_name,
	SUM(oi.total_sales) AS total_sales,
	SUM(oi.total_sales) / (SELECT SUM(total_sales) FROM order_items) * 100 AS percentage_contribution
FROM order_items AS oi
JOIN products AS p
ON p.product_id = oi.product_id
LEFT JOIN categories AS c 
ON c.category_id = p.category_id
GROUP BY 1, 2
ORDER BY 3 DESC;

/*
Compute the average order value for each customer
Include customers with more than 5 orders
*/

SELECT 
	c.customer_id,
	CONCAT(c.first_name, ' ', c.last_name) AS full_name,
	SUM(total_sales) / COUNT(o.order_id) AS average_order_value,
	COUNT(o.order_id) AS total_orders
FROM orders AS o
JOIN customers AS c
ON c.customer_id = o.customer_id
JOIN order_items AS oi
ON oi.order_id = o.order_id
GROUP BY 1, 2
HAVING COUNT(o.order_id) > 5;

/*
Query monthly total sales over the past 3 years
Display the sales trend, grouping by month; return current and last month sales
*/

SELECT 
	year,
	month,
	total_sales AS current_month_sales,
	LAG(total_sales, 1) OVER(ORDER BY year, month) AS last_month_sales
FROM
	(SELECT 
		EXTRACT(MONTH FROM o.order_date) AS month,
		EXTRACT(YEAR FROM o.order_date) AS year,
		ROUND(SUM(oi.total_sales::numeric), 2) AS total_sales
	FROM orders AS o
	JOIN order_items AS oi
	ON oi.order_id = o.order_id
	WHERE order_date >= CURRENT_DATE - INTERVAL '3 year'
	GROUP BY 1, 2
	ORDER BY year, month) AS t1

