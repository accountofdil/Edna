/*
Find the top 10 products with highest decreasing revenue ratio in terms of 2022 and 2023
Return product_id, product_name, category_name, 2022 revenue and 2023 revenue decrease ratio 
Decrease ratio = (cs - ls) / ls * 100 (cs = current_year, ls = last_year)
*/

WITH sales_2022
AS
	(SELECT 
		p.product_id,
		p.product_name,
		SUM(oi.total_sales) AS revenue
	FROM orders AS o
	JOIN order_items AS oi
	ON oi.order_id = o.order_id
	JOIN products AS p
	ON p.product_id = oi.product_id
	WHERE EXTRACT(YEAR FROM o.order_date) = 2022
	GROUP BY 1, 2),
sales_2023
AS
	(SELECT 
		p.product_id,
		p.product_name,
		SUM(oi.total_sales) AS revenue
	FROM orders AS o
	JOIN order_items AS oi
	ON oi.order_id = o.order_id
	JOIN products AS p
	ON p.product_id = oi.product_id
	WHERE EXTRACT(YEAR FROM o.order_date) = 2023
	GROUP BY 1, 2)
SELECT 
	s23.product_id,
	s22.revenue AS revenue_2022,
	s23.revenue AS revenue_2023,
	s22.revenue - s23.revenue AS revenue_difference,
	ROUND((s23.revenue - s22.revenue)::numeric / (s22.revenue)::numeric * 100, 2) AS revenue_decrease_ratio
FROM sales_2022 AS s22
JOIN sales_2023 AS s23
ON s22.product_id = s23.product_id
WHERE 
	s22.revenue > s23.revenue
	AND 
	ROUND((s23.revenue - s22.revenue)::numeric / (s22.revenue)::numeric * 100, 2) <> 0.00
ORDER BY 5 DESC
LIMIT 10;


