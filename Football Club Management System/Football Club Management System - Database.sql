-- Database Creation

IF NOT EXISTS (SELECT * FROM sys.databases WHERE name = 'football_club_management_system')
BEGIN
	CREATE DATABASE football_club_management_system;
END;
GO

USE football_club_management_system;
GO

IF NOT EXISTS (SELECT * FROM sys.schemas WHERE name = 'club')
BEGIN
	EXEC('CREATE SCHEMA club');
END;
GO

DROP TABLE IF EXISTS club.Teams;
CREATE TABLE club.Teams(
					TeamID INT IDENTITY(1, 1) NOT NULL,
					TeamName VARCHAR(100) NOT NULL,
					TeamType VARCHAR(30) NOT NULL CONSTRAINT DF_Teams_TeamType DEFAULT 'First Team',
					LeagueName VARCHAR(100) NOT NULL,
					HomeStadium VARCHAR(100) NOT NULL,
					EstYear INT NULL,
					CONSTRAINT PK_Teams PRIMARY KEY (TeamID),
					CONSTRAINT CK_Teams_TeamType CHECK (TeamType IN ('First Team', 'Reserves', 'U21', 'U18', 'Opponent')));
GO

SELECT * FROM club.Teams;

DROP TABLE IF EXISTS club.Staff;
CREATE TABLE club.Staff(
					StaffID INT IDENTITY(100, 1) NOT NULL,
					FirstName VARCHAR(50) NOT NULL,
					LastName VARCHAR(50) NOT NULL,
					Role VARCHAR(50) NOT NULL,
					Department VARCHAR(50) NOT NULL,
					HireDate DATE NOT NULL,
					MonthlySalary DECIMAL(10, 2) NOT NULL,
					IsActive BIT NOT NULL CONSTRAINT DF_Staff_IsActive DEFAULT 1,
					CONSTRAINT PK_Staff PRIMARY KEY (StaffID),
					CONSTRAINT CK_Staff_MonthlySalary CHECK (MonthlySalary > 0));
GO

SELECT * FROM club.Staff;

DROP TABLE IF EXISTS club.Players;
CREATE TABLE club.Players(
						PlayerID INT IDENTITY(1000, 1) NOT NULL,
						FirstName VARCHAR(50) NOT NULL,
						LastName VARCHAR(50) NOT NULL,
						DateOfBirth DATE NOT NULL,
						Nationality VARCHAR(50) NOT NULL,
						PrimaryPosition VARCHAR(20) NOT NULL,
						PreferredFoot VARCHAR(10) NOT NULL,
						HeightCM INT NOT NULL,
						WeightKG INT NOT NULL,
						TeamID INT NOT NULL,
						SquadNumber INT NULL,
						CONSTRAINT PK_Players PRIMARY KEY (PlayerID),
						CONSTRAINT FK_Players_Teams FOREIGN KEY (TeamID) REFERENCES club.Teams(TeamID),
						CONSTRAINT CK_Players_PrimaryPosition CHECK (PrimaryPosition IN ('Goalkeeper', 'Defender', 'Midfielder', 'Forward')),
						CONSTRAINT CK_Players_PreferredFoot CHECK (PreferredFoot IN ('Right', 'Left', 'Both')),
						CONSTRAINT UQ_Team_SquadNumber UNIQUE (TeamID, SquadNumber));
GO

SELECT * FROM club.Players;

DROP TABLE IF EXISTS club.Contracts;
CREATE TABLE club.Contracts(
						ContractID INT IDENTITY(5000, 1) NOT NULL,
						PlayerID INT NOT NULL,
						WeeklyWage DECIMAL(10, 2) NOT NULL,
						SigningBonus DECIMAL(12, 2) NOT NULL CONSTRAINT DF_Contracts_SigningBonus DEFAULT 0.00,
						GoalBonus DECIMAL(8, 2) NULL CONSTRAINT DF_Contracts_GoalBonus DEFAULT 0.00,
						StartDate DATE NOT NULL,
						EndDate DATE NOT NULL,
						ReleaseClause DECIMAL(12, 2) NULL,
						ContractStatus VARCHAR(20) NOT NULL CONSTRAINT DF_Contracts_ContractStatus DEFAULT 'Active',
						CONSTRAINT PK_Contracts PRIMARY KEY (ContractID),
						CONSTRAINT FK_Contracts_Players FOREIGN KEY (PlayerID) REFERENCES club.Players(PlayerID),
						CONSTRAINT CK_Contracts_Dates CHECK (EndDate > StartDate),
						CONSTRAINT CK_Contracts_ContractStatus CHECK (ContractStatus IN ('Active', 'Expired', 'Terminated', 'Pending')));
GO

SELECT * FROM club.Contracts;

DROP TABLE IF EXISTS club.Matches;
CREATE TABLE club.Matches(
						MatchID INT IDENTITY(2000, 1) NOT NULL,
						MatchDate DATETIME2 NOT NULL,
						HomeTeamID INT NOT NULL,
						AwayTeamID INT NOT NULL,
						Competition VARCHAR(50) NOT NULL,
						Season VARCHAR(10) NOT NULL,
						HomeGoals INT CONSTRAINT DF_Matches_HomeGoals DEFAULT 0,
						AwayGoals INT CONSTRAINT DF_Matches_AwayGoals DEFAULT 0,
						Attendance INT NULL,
						MatchStatus VARCHAR(20) NOT NULL CONSTRAINT DF_Matches_MatchStatus DEFAULT 'Scheduled',
						CONSTRAINT PK_Matches PRIMARY KEY (MatchID),
						CONSTRAINT FK_Matches_HomeTeam FOREIGN KEY (HomeTeamID) REFERENCES club.Teams(TeamID),
						CONSTRAINT FK_Matches_AwayTeam FOREIGN KEY (AwayTeamID) REFERENCES club.Teams(TeamID),
						CONSTRAINT CK_Matches_Teams CHECK (HomeTeamID <> AwayTeamID),
						CONSTRAINT CK_Matches_MatchStatus CHECK (MatchStatus IN ('Scheduled', 'Completed', 'Postponed', 'Cancelled')));
GO

SELECT * FROM club.Matches; 

DROP TABLE IF EXISTS club.PlayerMatchStats;
