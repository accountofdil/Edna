SELECT
	s.name AS SchemaName,
	t.name AS TableName,
	p.rows AS TotalRows,
	t.create_date AS CreatedDate
FROM sys.tables AS t
INNER JOIN sys.schemas AS s
ON t.schema_id = s.schema_id
INNER JOIN sys.partitions AS p
ON t.object_id = p.object_id AND p.index_id IN (0, 1)
WHERE s.name = 'club'
ORDER BY t.name;
GO
