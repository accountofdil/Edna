								MinutesPlayed INT NOT NULL CONSTRAINT DF_PlayerMatchStats_MinutesPlayed DEFAULT 0,
								GoalsScored INT NOT NULL CONSTRAINT DF_PlayerMatchStats_GoalsScored DEFAULT 0,
								Assists INT NOT NULL CONSTRAINT DF_PlayerMatchStats_Assists DEFAULT 0,
								ShotsOnTarget INT NOT NULL CONSTRAINT DF_PlayerMatchStats_ShotsOnTarget DEFAULT 0,
								PassesCompleted INT NOT NULL CONSTRAINT DF_PlayerMatchStats_PassesCompleted DEFAULT 0,
								PassesAttempted INT NOT NULL CONSTRAINT DF_PlayerMatchStats_PassesAttempted DEFAULT 0,
								TacklesWon INT NOT NULL CONSTRAINT DF_PlayerMatchStats_TacklesWon DEFAULT 0,
								YellowCards INT NOT NULL CONSTRAINT DF_PlayerMatchStats_YellowCards DEFAULT 0,
								RedCards INT NOT NULL CONSTRAINT DF_PlayerMatchStats_RedCards DEFAULT 0,
